"""Package the approved paintover without redrawing or rotating any pixels.

Requires numpy and Pillow. Run from any directory with no arguments.
The white source stays unchanged; only connected exterior background becomes
transparent in the runtime atlas. Ground anchors come from the real 3D render.
"""
from collections import deque
import json
from pathlib import Path
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'art-source/buildings/chamfered-corners'
OUTPUT = ROOT / 'assets/pizza/city/italian-chamfered-corners-3d-v1.png'
NAMES = ['Ockerfarbenes Eckhaus mit Uhr und roten Läden',
         'Elfenbeinfarbenes Eckhaus mit grünen Läden',
         'Korallenfarbenes Eckhaus mit Markise und blaugrünen Läden',
         'Goldgelbes Eckhaus mit bordeauxroten Läden']


def exterior_background(rgb):
    """Flood from canvas edges; preserve enclosed light window/stone pixels."""
    values = rgb.astype(np.int16)
    light = (values.min(axis=2) >= 235) & (np.ptp(values, axis=2) <= 22)
    height, width = light.shape
    outside = np.zeros_like(light)
    queue = deque()
    def visit(x, y):
        if 0 <= x < width and 0 <= y < height and light[y, x] and not outside[y, x]:
            outside[y, x] = True
            queue.append((x, y))
    for x in range(width):
        visit(x, 0)
        visit(x, height - 1)
    for y in range(height):
        visit(0, y)
        visit(width - 1, y)
    while queue:
        x, y = queue.popleft()
        visit(x - 1, y)
        visit(x + 1, y)
        visit(x, y - 1)
        visit(x, y + 1)
    return outside


def main():
    rgb = np.asarray(Image.open(SOURCE / 'paintover.png').convert('RGB'))
    height, width = rgb.shape[:2]
    geometry = json.loads((SOURCE / 'render-metadata.json').read_text())
    assert width == height, 'The approved sprite sheet must remain square.'
    sx, sy = width / geometry['canvas'][0], height / geometry['canvas'][1]
    assert abs(sx - sy) < 1e-12, 'No nonuniform rescaling of the approved sheet.'
    outside = exterior_background(rgb)
    rgba = np.dstack((rgb, np.where(outside, 0, 255).astype(np.uint8)))
    # Keep the original RGB data, including the foreground, exactly unchanged.
    assert np.array_equal(rgba[:, :, :3], rgb)
    Image.fromarray(rgba).save(OUTPUT)
    frames = []
    for row, name in enumerate(NAMES):
        for col, direction in enumerate(geometry['directions']):
            x0, x1 = round(col * width / 4), round((col + 1) * width / 4)
            y0, y1 = round(row * height / 4), round((row + 1) * height / 4)
            ys, xs = np.where(rgba[y0:y1, x0:x1, 3] > 0)
            assert len(xs), f'Missing sprite {row}/{col}'
            left, top = max(x0, x0 + int(xs.min()) - 2), max(y0, y0 + int(ys.min()) - 2)
            right, bottom = min(x1, x0 + int(xs.max()) + 3), min(y1, y0 + int(ys.max()) + 3)
            corners = [[round((col * 512 + x) * sx, 6), round((row * 512 + y) * sy, 6)]
                       for x, y in geometry['foundationCorners']]
            frames.append({
                # Stable IDs/families preserve existing deterministic city layouts.
                'id': f'clock-corner-{row}-{direction}',
                'name': f'{name} · {direction.upper()}',
                'crop': [left, top, right - left, bottom - top],
                'corners': corners, 'worldWidth': 103,
                'facadePixels': round(geometry['facadePixels'] * sy, 6),
                'storeys': 2, 'roof': 'chamfered-hip', 'shape': 'chamfered',
                'clock': row == 0, 'cornerDirection': direction,
                'buildingFamily': f'clock-corner-family-{row}',
                'modelYaw': geometry['yawDegrees'][col],
                'modelSource': 'art-source/buildings/chamfered-corners',
                'chimney': {'type': 'paired terracotta pots' if row == 2 else 'capped stone',
                            'position': geometry['chimneyWorldPosition']},
                'roofLines': [],
            })
    content = '// Generated by tools/prepare_corner_sprites.py. Do not hand-edit calibration.\n'
    content += '// One physical mesh per family, orthographic camera, yaw 0/90/180/270.\n'
    content += 'export const CORNER_BUILDING_ART=' + json.dumps(frames, ensure_ascii=False, indent=2) + ';\n'
    (ROOT / 'pizza-city-corner-art.js').write_text(content)
    assert len(frames) == 16
    print(f'Prepared {len(frames)} fixed-view frames: {OUTPUT.relative_to(ROOT)}, {width}x{height} RGBA.')
    print(f'Exterior alpha: {outside.mean():.1%}; foreground RGB unchanged; calibration from 3D geometry.')


if __name__ == '__main__':
    main()
